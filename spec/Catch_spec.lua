describe("Catch", function()
	local ns, m

	local function wolf(guid)
		return { name = "Wolf", level = 10, guid = guid }
	end

	before_each(function()
		ns = LoadAddonFile("src/Catch.lua", {})
		m = ns.Catch.new()
	end)

	it("has the window constants", function()
		assert.equal(3, ns.Catch.STOP_GRACE)
		assert.equal(20, ns.Catch.MAX_LIFE)
		assert.equal(5, ns.Catch.SHADOWBURN)
	end)

	it("nothing is current without a capture", function()
		assert.is_nil(m:current(10))
		assert.is_nil(m:take(10))
	end)

	it("a shard during the Drain Soul channel belongs to the target", function()
		m:startCapture("drainsoul", wolf("g1"), "cast1", 10)
		local c = m:current(14)
		assert.equal("drainsoul", c.kind)
		assert.equal("Wolf", c.info.name)
		assert.equal("g1", c.info.guid)
	end)

	it("counts up to 3 s after the channel stops, not after", function()
		m:startCapture("drainsoul", wolf(), "cast1", 10)
		m:channelStopped("cast1", 12)
		assert.is_not_nil(m:current(14.9))
		assert.is_nil(m:current(15.1))
	end)

	it("a stop for another cast leaves the capture alone; a stop without ids counts", function()
		m:startCapture("drainsoul", wolf(), "cast1", 10)
		m:channelStopped("other", 11)
		assert.is_not_nil(m:current(20))
		m:channelStopped(nil, 21)
		assert.is_not_nil(m:current(23.9))
		assert.is_nil(m:current(24.1))
	end)

	it("a capture without a cast id stops on any Drain Soul stop", function()
		m:startCapture("drainsoul", wolf(), nil, 10)
		m:channelStopped("cast9", 11)
		assert.is_nil(m:current(14.1))
	end)

	it("lives at most 20 s even with no stop event", function()
		m:startCapture("drainsoul", wolf(), "cast1", 10)
		assert.is_not_nil(m:current(29.9))
		assert.is_nil(m:current(30.1))
	end)

	it("a late stop cannot stretch past the 20 s cap", function()
		m:startCapture("drainsoul", wolf(), "cast1", 10)
		m:channelStopped("cast1", 29)
		assert.is_nil(m:current(30.5))
	end)

	it("an unreadable channel start clears the capture", function()
		m:startCapture("drainsoul", wolf(), "cast1", 10)
		m:restricted(true, 11)
		assert.is_nil(m:current(11))
	end)

	it("any other unreadable spell event caps the capture at now + 3", function()
		m:startCapture("drainsoul", wolf(), "cast1", 10)
		m:restricted(false, 11)
		assert.is_not_nil(m:current(13.9))
		assert.is_nil(m:current(14.1))
		-- it never extends an earlier expiry
		m:startCapture("drainsoul", wolf(), "cast2", 20)
		m:channelStopped("cast2", 21)
		m:restricted(false, 23)
		assert.is_nil(m:current(24.1))
	end)

	it("Shadowburn counts for 5 s + 3 s after the cast", function()
		m:startCapture("shadowburn", wolf(), "sb", 10)
		assert.is_not_nil(m:current(17.9))
		assert.is_nil(m:current(18.1))
	end)

	it("a Drain Soul stop does not shorten a Shadowburn capture", function()
		m:startCapture("shadowburn", wolf(), "sb", 10)
		m:channelStopped(nil, 10.5)
		assert.is_not_nil(m:current(17))
	end)

	it("a hidden name gives a capture marked unknown", function()
		m:startCapture("drainsoul", { unknown = true, isPlayer = true }, "cast1", 10)
		local c = m:take(11)
		assert.is_true(c.info.unknown)
		assert.is_true(c.info.isPlayer)
	end)

	it("take hands a capture out once; current then sees nothing", function()
		m:startCapture("drainsoul", wolf(), "cast1", 10)
		assert.is_not_nil(m:take(11))
		assert.is_nil(m:take(11))
		assert.is_nil(m:current(11))
	end)

	it("a new channel on the same target replaces the old capture", function()
		m:startCapture("drainsoul", { name = "Wolf", guid = "g1" }, "cast1", 10)
		m:channelStopped("cast1", 11)
		m:startCapture("drainsoul", { name = "Wolf", guid = "g1", level = 11 }, "cast2", 12)
		local c = m:take(12.5)
		assert.equal("cast2", c.castGUID)
		assert.is_nil(m:take(12.5))
	end)

	it("a new channel on another target replaces the old once the old one's grace is over", function()
		m:startCapture("drainsoul", { name = "Wolf", guid = "g1" }, "cast1", 10)
		m:channelStopped("cast1", 11)
		m:startCapture("drainsoul", { name = "Boar", guid = "g2" }, "cast2", 12)
		assert.equal("Boar", m:current(14.5).info.name)
	end)

	it("two live captures on different targets are ambiguous: no capture", function()
		m:startCapture("drainsoul", { name = "Wolf", guid = "g1" }, "cast1", 10)
		m:channelStopped("cast1", 11)
		m:startCapture("drainsoul", { name = "Boar", guid = "g2" }, "cast2", 12)
		assert.is_nil(m:take(13))
		assert.equal("Boar", m:take(14.5).info.name)
	end)

	it("a used capture does not make the next one ambiguous", function()
		m:startCapture("drainsoul", { name = "Wolf", guid = "g1" }, "cast1", 10)
		m:channelStopped("cast1", 11)
		assert.equal("Wolf", m:take(11.1).info.name)
		m:startCapture("drainsoul", { name = "Boar", guid = "g2" }, "cast2", 12)
		assert.equal("Boar", m:take(12.5).info.name)
	end)

	it("a new channel caps an old capture whose stop was missed", function()
		m:startCapture("drainsoul", { name = "Wolf", guid = "g1" }, "cast1", 10)
		m:startCapture("drainsoul", { name = "Boar", guid = "g2" }, "cast2", 15)
		assert.is_nil(m:current(16)) -- Wolf still within 3 s of Boar's start
		assert.equal("Boar", m:current(18.1).info.name)
	end)

	it("unknown targets without a GUID never count as the same target", function()
		m:startCapture("drainsoul", { unknown = true }, "cast1", 10)
		m:channelStopped("cast1", 11)
		m:startCapture("drainsoul", { unknown = true }, "cast2", 12)
		assert.is_nil(m:current(12.5))
	end)
end)
