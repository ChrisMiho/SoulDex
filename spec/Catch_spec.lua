describe("Catch", function()
	local ns, m

	before_each(function()
		ns = LoadAddonFile("src/Catch.lua", {})
		m = ns.Catch.new()
	end)

	it("drain active at death queues a candidate", function()
		m:noteUnit("g1", { name = "Wolf", level = 10, family = "Wolf" })
		m:noteAura("g1", "drain", 8)
		m:noteDeath("g1", "Wolf", 10)
		assert.is_true(m:hasPending(10.5))
		local c = m:takeCandidate(10.5)
		assert.equals("g1", c.guid)
		assert.equals("Wolf", c.info.name)
		assert.equals(10, c.info.level)
		assert.equals("Wolf", c.info.family)
		assert.is_nil(m:takeCandidate(10.5))
	end)

	it("aura removed just before death still counts", function()
		m:noteAura("g1", "drain", 5)
		m:noteAuraGone("g1", "drain", 10.0)
		m:noteDeath("g1", "Wolf", 10.5)
		assert.is_not_nil(m:takeCandidate(11))
	end)

	it("aura removed long before death does not count", function()
		m:noteAura("g1", "drain", 5)
		m:noteAuraGone("g1", "drain", 10)
		m:noteDeath("g1", "Wolf", 12)
		assert.is_nil(m:takeCandidate(12))
	end)

	it("shadowburn within 5 s counts; after 5 s does not", function()
		m:noteAura("a", "shadowburn", 10)
		m:noteDeath("a", "A", 14.5)
		assert.is_not_nil(m:takeCandidate(15))
		m:noteAura("b", "shadowburn", 10)
		m:noteDeath("b", "B", 15.5)
		assert.is_nil(m:takeCandidate(16))
	end)

	it("death with no aura queues nothing", function()
		m:noteUnit("g1", { name = "Wolf" })
		m:noteDeath("g1", "Wolf", 10)
		assert.is_false(m:hasPending(10))
		assert.is_nil(m:takeCandidate(10))
	end)

	it("expires candidates after the window", function()
		m:noteAura("g1", "drain", 8)
		m:noteDeath("g1", "Wolf", 10)
		assert.is_nil(m:takeCandidate(13.5))
		assert.is_false(m:hasPending(13.5))
	end)

	it("two deaths, two shards, oldest first", function()
		m:noteAura("a", "drain", 1)
		m:noteAura("b", "drain", 1)
		m:noteDeath("a", "A", 10)
		m:noteDeath("b", "B", 11)
		assert.equals("a", m:takeCandidate(11.5).guid)
		assert.equals("b", m:takeCandidate(11.5).guid)
		assert.is_nil(m:takeCandidate(11.5))
	end)

	it("a guid cannot queue twice for the same death", function()
		m:noteAura("a", "drain", 1)
		m:noteDeath("a", "A", 10)
		m:noteDeath("a", "A", 10.1)
		assert.is_not_nil(m:takeCandidate(10.5))
		assert.is_nil(m:takeCandidate(10.5))
	end)

	it("name comes from the combat log when nothing was cached", function()
		m:noteAura("g1", "drain", 8)
		m:noteDeath("g1", "Mystery", 10)
		local c = m:takeCandidate(10.5)
		assert.equals("Mystery", c.info.name)
		assert.is_nil(c.info.level)
		assert.is_nil(c.info.family)
		assert.is_nil(c.info.classification)
	end)

	it("later noteUnit calls merge, keeping non-nil fields", function()
		m:noteUnit("g1", { name = "Wolf", level = 10 })
		m:noteUnit("g1", { family = "Wolf", level = 11 })
		m:noteAura("g1", "drain", 8)
		m:noteDeath("g1", "Wolf", 10)
		local c = m:takeCandidate(10.5)
		assert.equals(11, c.info.level)
		assert.equals("Wolf", c.info.family)
	end)

	it("drops stale cache entries on death", function()
		m:noteUnit("old", { name = "Old", level = 5 }, 0)
		m:noteAura("x", "drain", 999)
		m:noteDeath("x", "X", 1000)
		m:noteAura("old", "drain", 1001)
		m:noteDeath("old", "Old", 1002)
		local _ = m:takeCandidate(1000.5)
		local c = m:takeCandidate(1002.5)
		assert.equals("Old", c.info.name)
		assert.is_nil(c.info.level)
	end)
end)
